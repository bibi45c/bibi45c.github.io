export function getMessages(locale = "en") {
  return messages[locale] ?? messages.en;
}

// Fills "{name}" placeholders, e.g. formatMessage(t.showingOf, { shown: 4, total: 62 }).
export function formatMessage(template, values) {
  return template.replace(/\{(\w+)\}/g, (match, key) => (key in values ? String(values[key]) : match));
}

export function postCountLabel(t, count) {
  return formatMessage(count === 1 ? t.postsUnitOne : t.postsUnit, { count });
}

export function unlocalizedPath(pathname) {
  const path = pathname.replace(/\/+$/, "") || "/";
  return path === "/zh" ? "/" : path.startsWith("/zh/") ? path.slice(3) : path;
}

export function localizedPath(path, locale = "en") {
  const [, pathname, suffix] = path.match(/^([^?#]*)(.*)$/);
  const base = unlocalizedPath(pathname);
  const prefix = locale === "zh" ? "/zh" : "";
  return `${prefix}${base === "/" ? "/" : `${base}/`}${suffix}`;
}

export function pageMetadata(key, locale = "en") {
  const paths = { home: "/", blog: "/blog", projects: "/project", about: "/about" };
  const t = getMessages(locale);
  return {
    title: key === "home" ? (locale === "zh" ? "bibi45 | 技术博客" : "bibi45 | Developer") : `${t.nav[key]} | bibi45`,
    description: t.description,
    alternates: {
      canonical: localizedPath(paths[key], locale),
      languages: { en: localizedPath(paths[key], "en"), "zh-CN": localizedPath(paths[key], "zh"), "x-default": localizedPath(paths[key], "en") },
    },
  };
}
